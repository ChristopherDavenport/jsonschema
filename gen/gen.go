// Package gen turns a JSON Schema document into Go source: named types plus
// Validate methods whose inline checks mirror the jsonschema validation engine,
// so the generated code enforces the schema with no third-party runtime
// dependency (only the first-party xvalid helpers).
package gen

import (
	"encoding/json"
	"fmt"

	"github.com/ChristopherDavenport/jsonschema/dialect"
	"github.com/ChristopherDavenport/jsonschema/gotype"
	"github.com/ChristopherDavenport/jsonschema/ir"
	"github.com/ChristopherDavenport/jsonschema/loader"
)

// Config controls code generation.
type Config struct {
	// Package is the generated package name.
	Package string
	// RootName is the Go type name for the root schema.
	RootName string
	// BaseURI is the retrieval URI used to resolve references in the document.
	BaseURI string
	// AssertFormat emits `format` checks in Validate methods when true.
	AssertFormat bool
	// DefaultDraft is assumed when the document has no $schema keyword.
	DefaultDraft dialect.Draft
	// EngineFallback makes Validate for types that use keywords the generator
	// cannot mirror inline (if/then/else, dependentSchemas, not, allOf) delegate
	// to the embedded schema + runtime engine, trading a dependency on the
	// jsonschema package for full conformance.
	EngineFallback bool
	// OmitRequiredChecks suppresses the required-property presence checks in the
	// generated UnmarshalJSON, so decoding stays lenient toward missing required
	// fields. The structural decoding UnmarshalJSON performs for embedded (allOf)
	// and tuple types is still emitted; MarshalJSON and Validate are unaffected.
	OmitRequiredChecks bool
	// HeaderComment overrides the "Code generated by jsonschema-gen; DO NOT EDIT."
	// banner emitted at the top of the file. Empty uses the default.
	HeaderComment string
}

// Generate parses a schema document and returns formatted Go source. Use
// [GenerateWithReport] to also learn what the output does not enforce.
func Generate(cfg Config, data []byte) ([]byte, error) {
	src, _, err := GenerateWithReport(cfg, data)
	return src, err
}

// GenerateWithReport is [Generate] plus a [Report] of the constraints the
// generated code does not enforce — the same information the NOTE comments in
// the output carry, so a caller can surface it at generation time.
func GenerateWithReport(cfg Config, data []byte) ([]byte, *Report, error) {
	var s ir.Schema
	if err := json.Unmarshal(data, &s); err != nil {
		return nil, nil, fmt.Errorf("gen: parse schema: %w", err)
	}

	draft := cfg.DefaultDraft
	if d, ok := dialect.Detect(s.SchemaURI); ok {
		draft = d
	}
	dialect.Normalize(&s, draft)

	ldr := loader.New()
	ldr.AddSchema(cfg.BaseURI, &s)

	model, err := gotype.Analyze(&s, ldr, gotype.Config{
		Package:  cfg.Package,
		RootName: cfg.RootName,
	})
	if err != nil {
		return nil, nil, err
	}

	return EmitModel(cfg, model, data)
}

// EmitModel renders Go source for an already-analyzed model. It is the
// lower-level entry point behind [GenerateWithReport], for a driver that does
// its own reference resolution and (possibly multi-root / multi-package)
// analysis via the gotype package and then emits each package's source itself.
// docBytes is the schema document used only for the engine-fallback embedding;
// it may be nil when Config.EngineFallback is false.
func EmitModel(cfg Config, model *gotype.Model, docBytes []byte) ([]byte, *Report, error) {
	e := &emitter{
		cfg:         cfg,
		model:       model,
		docBytes:    docBytes,
		hasValidate: map[string]bool{},
		isInterface: map[string]bool{},
		declByName:  map[string]*gotype.Decl{},
	}
	src, err := e.emit()
	if err != nil {
		return nil, nil, err
	}
	return src, &e.report, nil
}
